//! Writes the two self-contained C headers a binding build reads: one per
//! Wireshark release line, the same for every target, and one per target
//! holding the GLib and Gcrypt declarations every release line shares.

use crate::error::GenerateError;
use crate::public::{c_include_target, resolve_source_include, version_components};

use alloc::collections::BTreeSet;
use std::path::{Path, PathBuf};

/// Dissector headers kept in a release-line bundle. The rest describe
/// built-in dissectors a plugin does not call, and are most of a full set.
pub(crate) const DISSECTOR_HEADERS: &[&str] = &["packet-tcp.h", "packet-udp.h"];

/// Public headers emitted before the rest of the declared list.
pub(crate) const LEADING_HEADERS: &[&str] = &["epan/packet.h"];

/// Entry points of the dependency bundle. Every release line includes a subset
/// of these, so one bundle per target serves all of them.
const DEPENDENCY_ENTRY_POINTS: &[&str] = &["glib.h", "gmodule.h", "gcrypt.h"];

/// File name of the release-line bundle for `major.minor`.
pub fn wireshark_bundle_name(major: &str, minor: &str) -> String {
    format!("wireshark-{major}-{minor}.h")
}

/// File name of the dependency bundle for a Rust target OS and architecture.
pub fn dependency_bundle_name(target_os: &str, architecture: &str) -> String {
    format!("deps-{target_os}-{architecture}.h")
}

/// Writes the release-line bundle and returns the dependency headers it
/// includes directly, so the caller can check the dependency bundle has them.
pub(crate) fn write_wireshark_bundle(
    source_root: &Path,
    output: &Path,
    headers: &[&PathBuf],
    dependency_roots: &[PathBuf],
    version: Option<&str>,
) -> Result<BTreeSet<PathBuf>, GenerateError> {
    let source_root =
        std::fs::canonicalize(source_root).map_err(|_| GenerateError::InvalidSource)?;
    let (major, minor, patch) = version_components(version);
    let version = version.unwrap_or("0.0.0");
    if !version
        .bytes()
        .all(|byte| byte.is_ascii_digit() || byte == b'.')
    {
        return Err(GenerateError::InvalidSource);
    }
    let mut contents = format!(
        r#"/* Wireshark {version} public headers, generated by cargo-wireshark.
 * Include the matching deps-<os>-<arch>.h first. */
#ifndef LIBWIRESHARK_RS_WIRESHARK_H
#define LIBWIRESHARK_RS_WIRESHARK_H
/* Wireshark has X-macro headers that are included with caller-provided
 * expansions from implementation files. In an API umbrella they contribute
 * no declarations, so define their expansion hooks as empty. */
#define DEF_COND_ACE_TOKEN(VAL, VAR, STR)
#define DEF_COND_ACE_TOKEN_WITH_DATA(VAL, VAR, STR)
/* Some public dissector declarations use this opaque type before the header
 * that owns its forward declaration appears in Wireshark's public list. */
typedef struct _dcerpc_info dcerpc_info;
#ifndef __CONFIG_H__
#define __CONFIG_H__
#define PACKAGE "wireshark"
#define VERSION "{version}"
#define VERSION_MAJOR {major}
#define VERSION_MINOR {minor}
#define VERSION_MICRO {patch}
#define HAVE_PLUGINS 1
#define HAVE_LIBGCRYPT 1
#define PCRE2_CODE_UNIT_WIDTH 8
#if defined(_WIN32)
#define YY_NO_UNISTD_H
#endif
#endif
#ifndef __WS_VERSION_H__
#define __WS_VERSION_H__
#define WIRESHARK_VERSION_MAJOR {major}
#define WIRESHARK_VERSION_MINOR {minor}
#define WIRESHARK_VERSION_MICRO {patch}
#endif
"#
    );
    let mut walk = Walk::default();
    let mut dependencies = BTreeSet::new();
    for header in headers {
        walk.source(
            &source_root,
            &source_root.join(header),
            dependency_roots,
            &mut dependencies,
        )?;
    }
    for header in &walk.ordered {
        let label = relative_label(header, core::slice::from_ref(&source_root));
        embed(&mut contents, header, &label, |line| {
            c_include_target(line).is_some_and(|name| {
                name == "config.h"
                    || name == "ws_version.h"
                    || resolve_source_include(&source_root, header, name).is_some()
                    || resolve_dependency_include(dependency_roots, header, name).is_some()
            })
        })?;
    }
    contents.push_str("#endif /* LIBWIRESHARK_RS_WIRESHARK_H */\n");
    write(output, &contents)?;
    Ok(dependencies)
}

/// Writes the dependency bundle: GLib and Gcrypt headers reachable from
/// [`DEPENDENCY_ENTRY_POINTS`], each labelled relative to its include root.
///
/// Fails when a header in `required` (from [`write_wireshark_bundle`]) is
/// not part of the bundle.
pub(crate) fn write_dependency_bundle(
    output: &Path,
    dependency_roots: &[PathBuf],
    required: &BTreeSet<PathBuf>,
    target_os: &str,
    architecture: &str,
) -> Result<(), GenerateError> {
    let roots = dependency_roots
        .iter()
        .filter_map(|root| std::fs::canonicalize(root).ok())
        .collect::<Vec<_>>();
    let mut walk = Walk::default();
    for name in DEPENDENCY_ENTRY_POINTS {
        if let Some(entry) = roots
            .iter()
            .map(|root| root.join(name))
            .find(|path| path.is_file())
        {
            walk.dependency(&roots, &entry)?;
        }
    }
    if let Some(missing) = required.iter().find(|header| !walk.done.contains(*header)) {
        return Err(GenerateError::DependencyHeaders(format!(
            "{} is included by Wireshark but not reachable from {}",
            relative_label(missing, &roots),
            DEPENDENCY_ENTRY_POINTS.join(", ")
        )));
    }
    let mut contents = format!(
        r#"/* GLib and Gcrypt headers for {target_os}-{architecture}, generated by cargo-wireshark. */
#ifndef LIBWIRESHARK_RS_DEPS_H
#define LIBWIRESHARK_RS_DEPS_H
#define __GLIB_H_INSIDE__
#define __GLIB_GOBJECT_H_INSIDE__
#define __GIO_GIO_H_INSIDE__
#if defined(_WIN32) && !defined(_WIN32_WINNT)
#define _WIN32_WINNT 0x0A00
#endif
"#
    );
    for header in &walk.ordered {
        let label = relative_label(header, &roots);
        embed(&mut contents, header, &label, |line| {
            c_include_target(line)
                .is_some_and(|name| resolve_dependency_include(&roots, header, name).is_some())
        })?;
    }
    contents.push_str("#endif /* LIBWIRESHARK_RS_DEPS_H */\n");
    write(output, &contents)
}

/// Headers in the order a C compiler would finish them, each once.
#[derive(Default)]
struct Walk {
    stack: Vec<PathBuf>,
    done: BTreeSet<PathBuf>,
    ordered: Vec<PathBuf>,
}

impl Walk {
    fn source(
        &mut self,
        source_root: &Path,
        header: &Path,
        dependency_roots: &[PathBuf],
        dependencies: &mut BTreeSet<PathBuf>,
    ) -> Result<(), GenerateError> {
        let Some((canonical, source)) = self.enter(header)? else {
            return Ok(());
        };
        for name in source.lines().filter_map(c_include_target) {
            if let Some(path) = resolve_source_include(source_root, &canonical, name) {
                self.source(source_root, &path, dependency_roots, dependencies)?;
            } else if let Some(path) =
                resolve_dependency_include(dependency_roots, &canonical, name)
            {
                dependencies.insert(path);
            }
        }
        self.leave(canonical);
        Ok(())
    }

    fn dependency(&mut self, roots: &[PathBuf], header: &Path) -> Result<(), GenerateError> {
        let Some((canonical, source)) = self.enter(header)? else {
            return Ok(());
        };
        for name in source.lines().filter_map(c_include_target) {
            if let Some(path) = resolve_dependency_include(roots, &canonical, name) {
                self.dependency(roots, &path)?;
            }
        }
        self.leave(canonical);
        Ok(())
    }

    fn enter(&mut self, header: &Path) -> Result<Option<(PathBuf, String)>, GenerateError> {
        let canonical = std::fs::canonicalize(header)
            .map_err(|_| GenerateError::SourceHeaderRead(header.to_owned()))?;
        if self.stack.contains(&canonical) || self.done.contains(&canonical) {
            return Ok(None);
        }
        let source = std::fs::read_to_string(&canonical)
            .map_err(|_| GenerateError::SourceHeaderRead(canonical.clone()))?;
        self.stack.push(canonical.clone());
        Ok(Some((canonical, source)))
    }

    fn leave(&mut self, canonical: PathBuf) {
        self.stack.pop();
        self.done.insert(canonical.clone());
        self.ordered.push(canonical);
    }
}

pub(crate) fn resolve_dependency_include(
    dependency_roots: &[PathBuf],
    including: &Path,
    name: &str,
) -> Option<PathBuf> {
    let name = Path::new(name);
    let sibling = including.parent().map(|parent| parent.join(name));
    sibling
        .into_iter()
        .chain(dependency_roots.iter().map(|root| root.join(name)))
        .filter(|path| path.is_file())
        .filter_map(|path| std::fs::canonicalize(path).ok())
        .find(|path| {
            dependency_roots
                .iter()
                .filter_map(|root| std::fs::canonicalize(root).ok())
                .any(|root| path.starts_with(root))
        })
}

/// The path of `header` below the deepest root containing it, with `/`
/// separators: the label never names the machine the bundle was built on.
fn relative_label(header: &Path, roots: &[PathBuf]) -> String {
    roots
        .iter()
        .filter_map(|root| std::fs::canonicalize(root).ok())
        .filter_map(|root| header.strip_prefix(root).ok().map(Path::to_owned))
        .min_by_key(|relative| relative.components().count())
        .unwrap_or_else(|| PathBuf::from(header.file_name().unwrap_or_default()))
        .to_string_lossy()
        .replace('\\', "/")
}

fn embed(
    contents: &mut String,
    header: &Path,
    label: &str,
    skip: impl Fn(&str) -> bool,
) -> Result<(), GenerateError> {
    let source = std::fs::read_to_string(header)
        .map_err(|_| GenerateError::SourceHeaderRead(header.to_owned()))?;
    contents.push_str(&format!("\n/* Begin {label} */\n"));
    for line in source.lines().filter(|line| !skip(line)) {
        contents.push_str(line);
        contents.push('\n');
    }
    contents.push_str("/* End embedded header */\n");
    Ok(())
}

fn write(output: &Path, contents: &str) -> Result<(), GenerateError> {
    if let Some(parent) = output.parent() {
        std::fs::create_dir_all(parent)
            .map_err(|error| GenerateError::WriteFailed(error.to_string()))?;
    }
    std::fs::write(output, contents).map_err(|error| GenerateError::WriteFailed(error.to_string()))
}
